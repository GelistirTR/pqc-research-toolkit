import assert from 'node:assert/strict';
import { createCipheriv, createDecipheriv, randomBytes } from 'node:crypto';
import test from 'node:test';
import { ml_kem1024 } from '@noble/post-quantum/ml-kem.js';
import { ml_dsa87 } from '@noble/post-quantum/ml-dsa.js';
import { hkdf } from '@noble/hashes/hkdf.js';
import { sha512 } from '@noble/hashes/sha2.js';
import {
  encapsulate, generateKemKeyPair, generateSigningKeyPair,
  importKemPublicKey, importVerificationKey,
} from '../src/index.js';
import { keyPairFromBytes } from '../src/aead.js';

const message = Buffer.from('independent implementation interoperability');
const context = Buffer.from('interop/v1');
const kemPrefix = Buffer.from('30820632300b06096086480165030404030382062100', 'hex');
const dsaPrefix = Buffer.from('30820a32300b060960864801650304031303820a2100', 'hex');

// Independent HKDF implementation, using the documented alpha composition.
function expectedKey(secret, salt) {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(context.length);
  const info = Buffer.concat([
    Buffer.from('pqc-research-core/alpha1/ml-kem-1024/hkdf-sha512/aes256gcm\0'),
    length, context,
  ]);
  return hkdf(sha512, secret, salt, info, 32);
}

test('OpenSSL encapsulation -> independent noble ML-KEM decapsulation and HKDF', async () => {
  const noble = ml_kem1024.keygen();
  const imported = importKemPublicKey(Buffer.concat([kemPrefix, noble.publicKey]));
  const e = await encapsulate(imported);
  const { salt, key } = e.secret.deriveEncryptionKey(context);
  const packet = key.encrypt(message);
  const raw = ml_kem1024.decapsulate(e.ciphertext, noble.secretKey);
  const derived = expectedKey(raw, salt);
  const decipher = createDecipheriv('aes-256-gcm', derived, packet.nonce);
  decipher.setAuthTag(packet.tag);
  assert.deepEqual(Buffer.concat([decipher.update(packet.ciphertext), decipher.final()]), message);
  raw.fill(0); derived.fill(0); noble.secretKey.fill(0);
});

test('noble ML-KEM encapsulation and HKDF -> OpenSSL decapsulation', async () => {
  const recipient = await generateKemKeyPair();
  const spki = recipient.publicKey.exportSpki();
  assert.deepEqual(spki.subarray(0, 22), kemPrefix);
  const noble = ml_kem1024.encapsulate(spki.subarray(22));
  const salt = randomBytes(32);
  const derived = expectedKey(noble.sharedSecret, salt);
  const nonce = randomBytes(12);
  const cipher = createCipheriv('aes-256-gcm', derived, nonce);
  const ciphertext = Buffer.concat([cipher.update(message), cipher.final()]);
  const secret = await recipient.privateKey.decapsulate(noble.cipherText);
  const key = secret.deriveDecryptionKey(salt, context);
  assert.deepEqual(key.decrypt({ nonce, ciphertext, tag: cipher.getAuthTag() }), message);
  noble.sharedSecret.fill(0); derived.fill(0);
});

test('OpenSSL ML-DSA signature verifies in noble with the same FIPS context', async () => {
  const keys = await generateSigningKeyPair();
  const spki = keys.verificationKey.exportSpki();
  assert.deepEqual(spki.subarray(0, 22), dsaPrefix);
  const signature = await keys.signingKey.sign(message, context);
  assert.equal(ml_dsa87.verify(signature, message, spki.subarray(22), { context }), true);
  assert.equal(ml_dsa87.verify(signature, message, spki.subarray(22)), false);
});

test('noble ML-DSA signature verifies in OpenSSL with the same FIPS context', async () => {
  const keys = ml_dsa87.keygen();
  const verificationKey = importVerificationKey(Buffer.concat([dsaPrefix, keys.publicKey]));
  const signature = ml_dsa87.sign(message, keys.secretKey, { context });
  assert.equal(await verificationKey.verify(message, signature, context), true);
  assert.equal(await verificationKey.verify(message, signature, Buffer.alloc(0)), false);
  keys.secretKey.fill(0);
});

// NIST AES_GCM.pdf, GCM-AES256 Examples #1 and #2 (pages 21-24).
// These are fixed published vectors, not results generated by this implementation.
const vectorKey = Buffer.from('feffe9928665731c6d6a8f9467308308'.repeat(2), 'hex');
const vectorNonce = Buffer.from('cafebabefacedbaddecaf888', 'hex');

test('NIST AES-256-GCM example #1: empty plaintext', () => {
  const { decryptionKey, encryptionKey } = keyPairFromBytes(vectorKey);
  encryptionKey.destroy();
  assert.deepEqual(decryptionKey.decrypt({
    nonce: vectorNonce, ciphertext: Buffer.alloc(0),
    tag: Buffer.from('fd2caa16a5832e76aa132c1453eeda7e', 'hex'),
  }), Buffer.alloc(0));
});

test('NIST AES-256-GCM example #2: four-block plaintext', () => {
  const { decryptionKey, encryptionKey } = keyPairFromBytes(vectorKey);
  encryptionKey.destroy();
  const plaintext = decryptionKey.decrypt({
    nonce: vectorNonce,
    ciphertext: Buffer.from(
      '522dc1f099567d07f47f37a32a84427d643a8cdcbfe5c0c97598a2bd2555d1aa' +
      '8cb08e48590dbb3da7b08b1056828838c5f61e6393ba7a0abcc9f662898015ad', 'hex'),
    tag: Buffer.from('b094dac5d93471bdec1a502270e3cc6c', 'hex'),
  });
  assert.equal(plaintext.toString('hex'),
    'd9313225f88406e5a55909c5aff5269a86a7a9531534f7da2e4c303d8a318a72' +
    '1c3c0c95956809532fcf0e2449a6b525b16aedf5aa0de657ba637b391aafd255');
});
